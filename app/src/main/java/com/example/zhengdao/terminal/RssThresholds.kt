package com.example.zhengdao.terminal

/**
 * 内存告警阈值的**唯一登记处**（2026-10-12 立，§B 顺序 19）。
 *
 * ### 为什么是"两个数、一个家"，而不是"合并成一个数"
 * 这两处阈值看起来是同一个旋钮，其实**口径不同**，强行合并两边都会坏：
 *
 * | 常量 | 口径 | 量的是什么 | 高了会怎样 |
 * |---|---|---|---|
 * | [HEALTH_CARD_MB] | 体检卡（`ResMonitor.verdict()`） | 本 UID **除 App 自身**的全部进程（抱朴 serve ＋ PRoot guest ＋ 子进程）聚合 RSS | 卡片显黄色 ⚠ |
 * | [NOTIFY_MB] | 通知栏（`SessionService.buildNotification()`） | 只量**会话 shell 那一个进程**的 `VmRSS` | 通知里多一句「内存偏高」 |
 *
 * 取值依据（都不是拍的）：
 * - 体检卡的 800 MB：真机基线（2026-10-07）抱朴 serve 空闲 375–468 MB ⇒ 阈值须明显高于基线，
 *   否则一开抱朴就告警 = 狼来了。
 * - 通知栏的 3072 MB：只量一个 shell 进程，可它下面挂着 agent（node/python/tmux），
 *   正常跑起来就能上 GB ⇒ 用 800 会在通知栏每 30 秒刷一次假警报。
 *
 * ⇒ 反过来说：体检卡若用 3072 就永远不告警，通知栏若用 800 就天天告警。**两个都得留，但必须同源登记**，
 * 免得后人看到两处数字不一致又"顺手统一"一次（这就是本条待做的由来）。
 */
object RssThresholds {

    /** 体检卡口径：本 UID 聚合 RSS 超过它 ⇒ 体检卡显黄色 ⚠（不是红，资源占用没有一键修复）。 */
    const val HEALTH_CARD_MB = 800

    /** 通知栏口径：会话 shell 进程的 `VmRSS` 超过它 ⇒ 通知里提示「内存偏高，建议回到终端清理」。 */
    const val NOTIFY_MB = 3072L
}
