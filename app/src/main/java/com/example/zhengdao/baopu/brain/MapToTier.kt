package com.example.zhengdao.baopu.brain

/**
 * 三套映射共用一个切点函数：给定升序切点，返回"值 ≥ 几个切点"。
 * ⇒ 返回值天然落在 0..切点数，切点数恒为 3 ⇒ 恒落在 0..3（既有档的域）。
 */
internal object MapToTier {

    /** 既有档的上界（三套映射共用；冒出 4 档测试当场红）。 */
    const val TIER_MAX = 3

    /**
     * turgor：末窗群体放电率（放电数 ÷ 神经元数 ÷ 步数）→ 4 档。
     * 切点＝四个标称输入（档 0/1/2/3）在本网络里的**稳态末窗率**相邻中点。
     * 实测（四个物类 × 四档，见交付报告 §实测）：0 / 0.013–0.048 / 0.053–0.079 / 0.102–0.106。
     * 于是切点取 0.005（"有没有在放电"）、0.050、0.090（两个空隙的中点）。
     */
    private val RATE_CUTS = doubleArrayOf(0.005, 0.050, 0.090)

    /**
     * 适应：窗率斜率的**衰减量**（＝ -slope，单位"每窗"）→ 4 档。
     * 实测：0 / 0.00040–0.00044 / 0.00064–0.00067 / 0.00073–0.00074 ⇒ 切点取两个空隙中点。
     * 0＝几乎不衰减；3＝衰减最陡（持续刺激被自己的阈值压下去）。
     */
    private val ADAPT_CUTS = doubleArrayOf(0.0002, 0.00055, 0.00070)

    /**
     * 兴奋度：末窗群体平均膜电位 ÷ 基线阈值 → 4 档。
     * ⚠️ 实测**不是单调量**（见交付报告 §实测·落在定稿上的第一条）：静息 ≈ 0.00，
     * 一旦放电就跳到 0.74–1.46 且与强度不成正比（膜电位在复位与爬升之间打转）。
     * 所以这条只能分"静息 / 被驱动 / 明显被驱动"，分不出 1/2/3 的先后。
     * 本单不擅自换量（换了就违反"段 A 定稿是唯一读法"），只把读数记进报告，交段 C 裁定。
     */
    private val AROUSAL_CUTS = doubleArrayOf(0.30, 0.60, 0.95)

    /** 放电率 → turgor 档。 */
    fun turgor(spikeRate: Double): Int = cut(spikeRate, RATE_CUTS)

    /** 窗率斜率（负值＝衰减）→ 适应档。 */
    fun adaptation(slope: Double): Int = cut(-slope, ADAPT_CUTS)

    /** 群体平均膜电位（已归一化）→ 兴奋度档。 */
    fun arousal(meanPotential: Double): Int = cut(meanPotential, AROUSAL_CUTS)

    /** 升序切点 ⇒ 「值 ≥ 几个切点」。非有限值按 0 档（宁可不判，也不编一档出来）。 */
    private fun cut(value: Double, cuts: DoubleArray): Int {
        if (!value.isFinite()) return 0
        return cuts.count { value >= it }
    }
}
