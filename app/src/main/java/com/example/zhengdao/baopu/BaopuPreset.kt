            "## 工作计划（update_plan）\n" +
            "- **先判要不要列**：回答问题、一两步能完的活**不列**（列了是噪音）；\n" +
            "  超出三四步、或中间有先后依赖（先拿设备号才能装包、先备份才能改）才拉清单。\n" +
            "- **每条必须是「能判断做完没做完」的结果，不是动作**：\n" +
            "  「改布局」不合格；「底部栏四-tab 按 106dp 方案二甲落地并截图核对」才合格。\n" +
            "  最多 12 条、每条 ≤60 字；探路的活宁可拆细。\n" +
