// 第七百八十八批 · 段 B ③：刺激档 → 输入电流（rate coding 的编码端）。
// 依据：定稿 §三「刺激强度档 → 输入电流 I（0–3 档映射到 4 个电流值）」。
//
// 四个电流值怎么来的（写死，不插值、不外推、不按代理档反推）：
// 以基线阈值 θ0=1.0 为单位，用本包的 LIF 方程解「从静息到首次放电要几步」——
//   I=0.00：稳态 0 ⇒ 永不放电（档 0 就是"没有刺激"）
//   I=1.30：1.30(1-0.75^n) ≥ 1 ⇒ n ≥ 5.09 ⇒ 首脉冲在第 6 步（30 ms）
//   I=1.70：n ≥ 3.08 ⇒ 首脉冲第 4 步（20 ms）
//   I=2.40：n ≥ 1.90 ⇒ 首脉冲第 2 步（10 ms，已逼近不应期上限）
// 这四个数只由方程和步长决定，没有自由参数。
// 为什么档 1 不用 1.05（只比阈值高 5%）：实测那样会贴着阈值爬，是否放电取决于拓扑抽到
// 哪 8 条入边（0–0.037 之间乱跳），读数不可复现。1.30 有稳定的稳态放电率（≈0.03）。
package com.example.zhengdao.baopu.brain

/** 刺激档 → 输入电流的写死表（定稿 §四「映射表写死」，判据④不许新增档）。 */
internal object Encode {

    /** 刺激档上界（既有读数只有 0–3 四档）。 */
    const val MAX_TIER = 3

    /** 表本体：下标即刺激档。表长＝[MAX_TIER]+1，改长度测试当场红。 */
    private val CURRENT_BY_TIER = doubleArrayOf(0.0, 1.30, 1.70, 2.40)

    /**
     * 档 ⇒ 电流。越界抛异常（不外推、不夹取）：档是闭集，冒出第 5 档说明上游口径变了，
     * 必须当场红，而不是悄悄按 3 档算。
     */
    fun currentOf(tier: Int): Double {
        require(tier in 0..MAX_TIER) { "刺激档只收 0..$MAX_TIER，收到 $tier" }
        return CURRENT_BY_TIER[tier]
    }

    /** 表长自检（测试用；生产每次调用不查）。 */
    fun tableSize(): Int = CURRENT_BY_TIER.size
}
